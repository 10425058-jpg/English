import type { CEFRLevel, Exercise, IELTSReadingPassage } from '@english-quest/shared';
import { createIeltsReading, iEx } from './helpers';

export interface AcademicReadingSeed {
  id: string;
  sectionLabel: string;
  title: string;
  topic: string;
  cefrTarget: CEFRLevel;
  paragraphs: Array<{ label: string; text: string }>;
  tfng: {
    statement: string;
    answer: 'TRUE' | 'FALSE' | 'NOT GIVEN';
    explanation: string;
    explanationVi: string;
  };
  ynng: {
    claim: string;
    answer: 'YES' | 'NO' | 'NOT GIVEN';
    explanation: string;
    explanationVi: string;
  };
  heading: {
    targetParagraph: 'A' | 'B' | 'C';
    options: string[];
    correctAnswer: string;
    explanation: string;
    explanationVi: string;
  };
  summary: {
    prompt: string;
    correctAnswer: string;
    acceptableAnswers?: string[];
    explanation: string;
    explanationVi: string;
  };
  mcq: {
    prompt: string;
    options: string[];
    correctAnswer: string;
    explanation: string;
    explanationVi: string;
  };
}

export function buildAcademicPassage(seed: AcademicReadingSeed): IELTSReadingPassage {
  const fullContext = seed.paragraphs.map((p) => `[Paragraph ${p.label}] ${p.text}`).join('\n\n');
  const exercises: Exercise[] = [
    iEx({
      id: `${seed.id}-ex-1`,
      lessonId: seed.id,
      type: 'reading_comprehension',
      instruction: 'Do the following statements agree with the factual information in the passage? Choose TRUE, FALSE, or NOT GIVEN.',
      prompt: `[${seed.title}] Statement: "${seed.tfng.statement}"`,
      passage: fullContext,
      options: ['TRUE', 'FALSE', 'NOT GIVEN'],
      correctAnswer: seed.tfng.answer,
      explanation: seed.tfng.explanation,
      explanationVi: seed.tfng.explanationVi,
      difficulty: 3,
      skills: ['reading'],
    }),
    iEx({
      id: `${seed.id}-ex-2`,
      lessonId: seed.id,
      type: 'reading_comprehension',
      instruction: 'Does the statement agree with the claims/views of the writer? Choose YES, NO, or NOT GIVEN.',
      prompt: `[${seed.title}] Writer Claim Check: "${seed.ynng.claim}"`,
      passage: fullContext,
      options: ['YES', 'NO', 'NOT GIVEN'],
      correctAnswer: seed.ynng.answer,
      explanation: seed.ynng.explanation,
      explanationVi: seed.ynng.explanationVi,
      difficulty: 3,
      skills: ['reading'],
    }),
    iEx({
      id: `${seed.id}-ex-3`,
      lessonId: seed.id,
      type: 'reading_comprehension',
      instruction: `Match the most accurate thematic heading to Paragraph ${seed.heading.targetParagraph}.`,
      prompt: `Choose the best heading for Paragraph ${seed.heading.targetParagraph} of "${seed.title}":`,
      passage: fullContext,
      options: seed.heading.options,
      correctAnswer: seed.heading.correctAnswer,
      explanation: seed.heading.explanation,
      explanationVi: seed.heading.explanationVi,
      difficulty: 3,
      skills: ['reading'],
    }),
    iEx({
      id: `${seed.id}-ex-4`,
      lessonId: seed.id,
      type: 'fill_blank',
      instruction: 'Complete the summary note using ONE WORD ONLY taken accurately from the passage.',
      prompt: `[${seed.title}] ${seed.summary.prompt}`,
      passage: fullContext,
      correctAnswer: seed.summary.correctAnswer,
      acceptableAnswers: seed.summary.acceptableAnswers ?? [seed.summary.correctAnswer.toLowerCase()],
      explanation: seed.summary.explanation,
      explanationVi: seed.summary.explanationVi,
      difficulty: 3,
      skills: ['reading', 'vocabulary'],
    }),
    iEx({
      id: `${seed.id}-ex-5`,
      lessonId: seed.id,
      type: 'multiple_choice',
      instruction: 'Select the best evidence-backed answer according to the passage.',
      prompt: `[${seed.title}] ${seed.mcq.prompt}`,
      passage: fullContext,
      options: seed.mcq.options,
      correctAnswer: seed.mcq.correctAnswer,
      explanation: seed.mcq.explanation,
      explanationVi: seed.mcq.explanationVi,
      difficulty: 3,
      skills: ['reading'],
    }),
  ];

  return createIeltsReading({
    id: seed.id,
    pathway: 'academic',
    sectionLabel: seed.sectionLabel,
    title: seed.title,
    topic: seed.topic,
    cefrTarget: seed.cefrTarget,
    paragraphs: seed.paragraphs,
    questionTypesCovered: [
      'True / False / Not Given',
      'Yes / No / Not Given',
      'Matching Headings',
      'Summary Completion (1 Word)',
      'Academic Multiple Choice',
    ],
    exercises,
  });
}

